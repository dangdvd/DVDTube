// The player endpoint's answer → what can actually be played (port of `PlayerParser`; the
// DASH byte ranges, durations and audio details follow the iOS parser).

import { parseStoryboard, type ByteRange, type CaptionTrack, type PlayerInfo, type StreamFormat } from '@shared/models'
import { Errors } from '../errors'
import { JNode } from '../json'

export function parsePlayer(json: JNode, videoId: string, client: string | null = null, now = Date.now()): PlayerInfo {
  const playability = json.get('playabilityStatus')
  const status = playability.get('status').string ?? ''
  if (status !== 'OK') {
    const error = playability.at('errorScreen', 'playerErrorMessageRenderer')
    const reason =
      playability.get('reason').string ??
      error.get('reason').text ??
      error.get('subreason').text ??
      `Video không khả dụng (${status || 'không rõ'}).`
    if (status === 'LOGIN_REQUIRED') throw Errors.loginRequired(reason)
    throw Errors.unplayable(reason)
  }

  const details = json.get('videoDetails')
  const returned = details.get('videoId').string
  if (returned !== null && returned !== videoId) throw Errors.unplayable('YouTube trả về một video khác. Vui lòng thử lại.')

  const streaming = json.get('streamingData')
  const adaptive = streaming.get('adaptiveFormats').array.map(parseFormat).filter((f): f is StreamFormat => f !== null)
  const muxed = streaming.get('formats').array.map(parseFormat).filter((f): f is StreamFormat => f !== null)
  const hls = streaming.get('hlsManifestUrl').string
  const dash = streaming.get('dashManifestUrl').string
  if (!hls && adaptive.length === 0 && muxed.length === 0) throw Errors.noStreams()

  const captions: CaptionTrack[] = []
  for (const track of json.at('captions', 'playerCaptionsTracklistRenderer').get('captionTracks').array) {
    const base = track.get('baseUrl').string
    const code = track.get('languageCode').string
    if (!base || !code) continue
    captions.push({
      name: track.get('name').text ?? code,
      languageCode: code,
      baseUrl: base.startsWith('/') ? 'https://www.youtube.com' + base : base,
      isAutoGenerated: track.get('kind').string === 'asr',
      isTranslatable: track.get('isTranslatable').bool ?? false,
    })
  }

  const spec = json.at('storyboards', 'playerStoryboardSpecRenderer', 'spec').string
  return {
    videoId,
    title: details.get('title').string ?? '',
    author: details.get('author').string,
    channelId: details.get('channelId').string,
    lengthSeconds: details.get('lengthSeconds').int,
    viewCount: details.get('viewCount').long,
    shortDescription: details.get('shortDescription').string,
    isLive: details.get('isLive').bool ?? false,
    isLiveDvr: details.get('isLiveDvrEnabled').bool ?? false,
    thumbnail: details.get('thumbnail').bestImageUrl,
    hlsUrl: hls,
    dashUrl: dash,
    adaptiveFormats: adaptive,
    muxedFormats: muxed,
    captions,
    availableAt: now + Math.round(prerollAdSeconds(json) * 1000),
    storyboard: spec ? parseStoryboard(spec) : null,
    loudnessDb: json.at('playerConfig', 'audioConfig', 'loudnessDb').double,
    client,
  }
}

export function parseFormat(f: JNode): StreamFormat | null {
  // Formats with `signatureCipher` need the web player's JS to decode; skip them.
  const itag = f.get('itag').int
  const url = f.get('url').string
  const mime = f.get('mimeType').string
  if (itag === null || !url || !mime) return null
  const trackId = f.at('audioTrack', 'id').string
  const language = trackId ? trackId.split('.')[0] : ''
  return {
    itag,
    url,
    mimeType: mime,
    bitrate: f.get('bitrate').int ?? 0,
    width: f.get('width').int,
    height: f.get('height').int,
    fps: f.get('fps').int,
    contentLength: f.get('contentLength').long,
    qualityLabel: f.get('qualityLabel').string,
    audioTrackName: f.at('audioTrack', 'displayName').string,
    isDefaultAudio: f.at('audioTrack', 'audioIsDefault').bool ?? true,
    audioLanguage: language || null,
    initRange: byteRange(f.get('initRange')),
    indexRange: byteRange(f.get('indexRange')),
    approxDurationMs: f.get('approxDurationMs').long,
    audioSampleRate: f.get('audioSampleRate').int,
    audioChannels: f.get('audioChannels').int,
    colorInfo: colorInfo(f),
  }
}

/** `{"start": "0", "end": "740"}` → {start: 0, end: 740}. */
function byteRange(node: JNode): ByteRange | null {
  const start = node.get('start').long
  const end = node.get('end').long
  if (start === null || end === null || end < start) return null
  return { start, end }
}

/** "HDR" for PQ / HLG transfer functions or BT.2020 primaries; null for SDR. */
function colorInfo(f: JNode): string | null {
  const info = f.get('colorInfo')
  const transfer = info.get('transferCharacteristics').string ?? ''
  const primaries = info.get('primaries').string ?? ''
  if (
    transfer.includes('SMPTEST2084') ||
    transfer.includes('ARIB_STD_B67') ||
    primaries.includes('BT2020') ||
    (f.get('qualityLabel').string ?? '').includes('HDR')
  ) {
    return 'HDR'
  }
  return null
}

/**
 * YouTube refuses to serve the streams until a (skipped) pre-roll would have finished.
 * Sum the length (or skip offset) of every pre-roll ad, like yt-dlp.
 */
function prerollAdSeconds(json: JNode): number {
  const renderers: JNode[] = []
  for (const placement of json.get('adPlacements').array) {
    if (placement.at('adPlacementRenderer', 'config', 'adPlacementConfig', 'kind').string === 'AD_PLACEMENT_KIND_START') {
      renderers.push(...placement.at('adPlacementRenderer', 'renderer').findAll('instreamVideoAdRenderer'))
    }
  }
  for (const slot of json.get('adSlots').array) {
    if (slot.at('adSlotRenderer', 'adSlotMetadata', 'triggerEvent').string === 'SLOT_TRIGGER_EVENT_BEFORE_CONTENT') {
      renderers.push(...slot.findAll('instreamVideoAdRenderer'))
    }
  }
  let total = 0
  for (const renderer of renderers) {
    const skip = renderer.get('skipOffsetMilliseconds').double
    if (skip !== null) {
      total += skip / 1000
    } else {
      const vars = renderer.get('playerVars').string
      if (vars === null) continue
      const length = parseFloat(new URLSearchParams(vars).get('length_seconds') ?? '')
      if (Number.isFinite(length)) total += length
    }
  }
  return Math.min(total, 120)
}

/** The best H.264 stream not taller than `maxHeight` (else the smallest one). */
export function bestVideo(info: PlayerInfo, maxHeight: number): StreamFormat | null {
  const h264 = info.adaptiveFormats.filter((f) => f.mimeType.startsWith('video/') && f.mimeType.includes('avc1'))
  let best: StreamFormat | null = null
  for (const f of h264) {
    if ((f.height ?? 0) > maxHeight) continue
    if (!best || (f.height ?? 0) > (best.height ?? 0) || ((f.height ?? 0) === (best.height ?? 0) && f.bitrate > best.bitrate)) {
      best = f
    }
  }
  if (best) return best
  let smallest: StreamFormat | null = null
  for (const f of h264) if (!smallest || (f.height ?? 0) < (smallest.height ?? 0)) smallest = f
  return smallest
}

/** The best AAC stream of the original language. */
export function bestAudio(info: PlayerInfo): StreamFormat | null {
  const aac = info.adaptiveFormats.filter((f) => f.mimeType.startsWith('audio/') && f.mimeType.includes('mp4a'))
  const pick = (list: StreamFormat[]) => list.reduce<StreamFormat | null>((a, b) => (!a || b.bitrate > a.bitrate ? b : a), null)
  return pick(aac.filter((f) => f.isDefaultAudio)) ?? pick(aac)
}

function isSdr(f: StreamFormat): boolean {
  return !f.colorInfo
}

/** Tallest stream ≤ maxHeight (SDR first, then higher fps, then bitrate). */
function tallest(formats: StreamFormat[], maxHeight: number): StreamFormat | null {
  const fitting = formats.filter((f) => (f.height ?? 0) <= maxHeight && f.url)
  const pool = fitting.some(isSdr) ? fitting.filter(isSdr) : fitting
  return pool.reduce<StreamFormat | null>((best, f) => {
    if (!best) return f
    const dh = (f.height ?? 0) - (best.height ?? 0)
    if (dh !== 0) return dh > 0 ? f : best
    const df = (f.fps ?? 0) - (best.fps ?? 0)
    if (df !== 0) return df > 0 ? f : best
    return f.bitrate > best.bitrate ? f : best
  }, null)
}

/** The best Opus stream of the original language (VP9 downloads go into a .webm). */
export function bestOpus(info: PlayerInfo): StreamFormat | null {
  const opus = info.adaptiveFormats.filter((f) => f.mimeType.startsWith('audio/webm') && f.mimeType.includes('opus') && f.url)
  const pick = (list: StreamFormat[]) => list.reduce<StreamFormat | null>((a, b) => (!a || b.bitrate > a.bitrate ? b : a), null)
  return pick(opus.filter((f) => f.isDefaultAudio)) ?? pick(opus)
}

export interface DownloadPlan {
  video: StreamFormat | null
  audio: StreamFormat | null
  container: 'mp4' | 'webm' | 'm4a'
}

/**
 * Which streams a download uses. Above 1080p: an AV1 MP4 stream (+ AAC, merged into .mp4) when
 * it is taller than the best H.264 one, else VP9 WebM + Opus (.webm), else H.264 ≤ 1080p.
 */
export function downloadPlan(info: PlayerInfo, maxHeight: number, audioOnly: boolean): DownloadPlan {
  const aac = info.adaptiveFormats.find((f) => f.itag === 140 && f.isDefaultAudio && f.url) ?? bestAudio(info)
  if (audioOnly) return { video: null, audio: aac, container: 'm4a' }
  const h264 = bestVideo(info, Math.min(maxHeight, 1080))
  if (maxHeight > 1080) {
    const h264Height = h264?.height ?? 0
    const video = info.adaptiveFormats.filter((f) => f.mimeType.startsWith('video/'))
    const av1 = tallest(video.filter((f) => f.mimeType.startsWith('video/mp4') && f.mimeType.includes('av01')), maxHeight)
    if (av1 && (av1.height ?? 0) > h264Height && aac) return { video: av1, audio: aac, container: 'mp4' }
    const vp9 = tallest(video.filter((f) => f.mimeType.startsWith('video/webm') && /vp0?9/.test(f.mimeType)), maxHeight)
    const opus = bestOpus(info)
    if (vp9 && opus && (vp9.height ?? 0) > h264Height) return { video: vp9, audio: opus, container: 'webm' }
  }
  return { video: h264, audio: aac, container: 'mp4' }
}
